<?php

namespace Webkul\Account\Services;

use Carbon\CarbonInterface;
use Webkul\Account\Enums\DisplayType;
use Webkul\Account\Enums\MoveState;
use Webkul\Account\Enums\MoveType;
use Webkul\Account\Facades\Account as AccountFacade;
use Webkul\Account\Models\Expense;
use Webkul\Account\Models\Move;

/**
 * An expense paid straight from a bank or cash account, as one posted
 * journal entry: each expense (and tax) account debited, the account the
 * money left credited, on the expense date, with the vendor on every line.
 *
 * One builder for every caller (user, 2026-11-26): the Expenses screen
 * (ExpenseRecorder) and the Zoho Books import both write this entry, so
 * they cannot drift apart. The caller chooses the journal. The import uses
 * Miscellaneous Operations; the Expenses screen passes its Expense, which
 * is the only way an entry may sit in a bank or cash journal (plan #10 Z2,
 * Move::isExpenseEntryInItsJournal()). Without an Expense the journal rule
 * is unchanged, so a bank journal passed here alone is still replaced by
 * the general journal.
 *
 * Amounts: `amount` is in the company currency (the ledger's debit). For a
 * foreign-currency entry each line also carries `amount_currency`, in the
 * entry's currency; without it the two are the same. The credit line is the
 * sum of the debits in both, so the entry always balances in the company
 * currency. A line with `tax_line_id` is written as a tax line (display
 * type TAX, with its repartition line and base), which is what the tax
 * summary report reads.
 *
 * Totals and posting are DEKA's own (computeAccountMove, confirmMove), so the
 * lock date and the balance check apply as for an entry typed by hand.
 */
class ExpenseEntry
{
    /**
     * @param  list<array{account_id: int, amount: float, name: string, amount_currency?: float, tax_line_id?: int, tax_repartition_line_id?: int, tax_base_amount?: float}>  $lines
     */
    public function post(
        int $companyId,
        int $currencyId,
        int $journalId,
        CarbonInterface|string $date,
        array $lines,
        int $paidFromAccountId,
        string $paidFromLabel,
        ?int $partnerId = null,
        ?string $reference = null,
        ?string $narration = null,
        ?int $creatorId = null,
        ?Expense $expense = null,
    ): Move {
        $move = new Move([
            'move_type'   => MoveType::ENTRY,
            'state'       => MoveState::DRAFT,
            'company_id'  => $companyId,
            'journal_id'  => $journalId,
            'currency_id' => $currencyId,
            'partner_id'  => $partnerId,
            'date'        => $date,
            'reference'   => $reference,
            'narration'   => $narration,
            'creator_id'  => $creatorId,
        ]);

        if ($expense) {
            $move->forExpense($expense);
        }

        $move->save();

        $this->writeLines($move, $lines, $paidFromAccountId, $paidFromLabel, $partnerId, $creatorId);

        return AccountFacade::confirmMove(AccountFacade::computeAccountMove($move->refresh()));
    }

    /**
     * Rewrite an expense's posted entry in place (Z1: "editing rewrites the
     * entry"). Goes through DEKA's own reset to draft, which needs a reason
     * and is refused in a locked period, then posts again, which is refused
     * if the new date is locked. The entry keeps its number unless it moves
     * to another journal, which numbers it in that journal's sequence.
     *
     * Every line of the entry is replaced. That is safe here and only here:
     * the entry is the expense's alone (ownsMove()), an entry carries no
     * lines generated by accounting, and reset to draft has already undone
     * any reconciliation.
     *
     * @param  list<array{account_id: int, amount: float, name: string, amount_currency?: float, tax_line_id?: int, tax_repartition_line_id?: int, tax_base_amount?: float}>  $lines
     */
    public function rewrite(
        Move $move,
        Expense $expense,
        string $reason,
        int $currencyId,
        int $journalId,
        CarbonInterface|string $date,
        array $lines,
        int $paidFromAccountId,
        string $paidFromLabel,
        ?int $partnerId = null,
        ?string $reference = null,
        ?string $narration = null,
        ?int $creatorId = null,
    ): Move {
        $move->forExpense($expense);

        if ($move->state !== MoveState::DRAFT) {
            $move = AccountFacade::resetToDraftMove($move, $reason);
        }

        $move->lines()->get()->each->delete();

        $journalChanged = (int) $move->journal_id !== $journalId;

        $move->fill([
            'journal_id'  => $journalId,
            'currency_id' => $currencyId,
            'partner_id'  => $partnerId,
            'date'        => $date,
            'reference'   => $reference,
            'narration'   => $narration,
        ]);

        if ($journalChanged) {
            $move->unsetRelation('journal');
            $move->name = null;
            $move->computeName();
        }

        $move->save();

        $this->writeLines($move, $lines, $paidFromAccountId, $paidFromLabel, $partnerId, $creatorId);

        return AccountFacade::confirmMove(AccountFacade::computeAccountMove($move->refresh()));
    }

    /**
     * @param  list<array{account_id: int, amount: float, name: string, amount_currency?: float, tax_line_id?: int, tax_repartition_line_id?: int, tax_base_amount?: float}>  $lines
     */
    protected function writeLines(Move $move, array $lines, int $paidFromAccountId, string $paidFromLabel, ?int $partnerId, ?int $creatorId): void
    {
        $total = 0.0;
        $totalCurrency = 0.0;

        foreach ($lines as $line) {
            $amount = round((float) $line['amount'], 2);
            $amountCurrency = round((float) ($line['amount_currency'] ?? $amount), 2);

            $total += $amount;
            $totalCurrency += $amountCurrency;

            $this->line($move, (int) $line['account_id'], $partnerId, $line['name'], $amount, 0.0, $amountCurrency, $creatorId, $line);
        }

        $this->line($move, $paidFromAccountId, $partnerId, $paidFromLabel, 0.0, round($total, 2), -round($totalCurrency, 2), $creatorId);
    }

    /**
     * @param  array<string, mixed>  $tax
     */
    protected function line(Move $move, int $accountId, ?int $partnerId, string $name, float $debit, float $credit, float $amountCurrency, ?int $creatorId, array $tax = []): void
    {
        $isTaxLine = filled($tax['tax_line_id'] ?? null);

        $move->lines()->create([
            'name'                    => $name,
            'date'                    => $move->date,
            'creator_id'              => $creatorId,
            'parent_state'            => $move->state,
            // Set explicitly: a line saved without a display type is costed
            // through the "default" branch of MoveLine::computeAccountId(),
            // which replaces account_id with the journal's default account,
            // and MoveCalculator zeroes the totals of anything not PRODUCT.
            // A tax line is TAX with its tax: computeAccountId() then keeps
            // the repartition account, and the tax summary report finds it.
            'display_type'            => $isTaxLine ? DisplayType::TAX : DisplayType::PRODUCT,
            'account_id'              => $accountId,
            'partner_id'              => $partnerId,
            'company_id'              => $move->company_id,
            'currency_id'             => $move->currency_id,
            'debit'                   => $debit,
            'credit'                  => $credit,
            'balance'                 => $debit - $credit,
            'amount_currency'         => $amountCurrency,
            'tax_line_id'             => $isTaxLine ? (int) $tax['tax_line_id'] : null,
            'tax_repartition_line_id' => $isTaxLine ? ($tax['tax_repartition_line_id'] ?? null) : null,
            'tax_base_amount'         => $isTaxLine ? (float) ($tax['tax_base_amount'] ?? 0.0) : 0.0,
        ]);
    }
}
