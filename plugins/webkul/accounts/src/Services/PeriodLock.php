<?php

namespace Webkul\Account\Services;

use Carbon\CarbonImmutable;
use Carbon\CarbonInterface;
use Illuminate\Auth\Access\AuthorizationException;
use Illuminate\Validation\ValidationException;
use Webkul\Account\Enums\MoveState;
use Webkul\Account\Exceptions\PeriodLockedException;
use Webkul\Account\Models\LockDate;
use Webkul\Account\Models\Move;
use Webkul\Account\Models\MoveLine;
use Webkul\Security\Models\User;

/**
 * The company lock date (accounting plan #7, A2, 2026-11-12): once an
 * accountant closes a month, nobody may post, change, reset, cancel or delete
 * a posted entry dated on or before it.
 *
 * Enforced from the Move and MoveLine model hooks, not from the screens, so
 * the API, imports, Logistics' ExpensePoster and every action share one rule.
 * Drafts stay editable: they are not in the ledger. Paying or reconciling a
 * locked invoice stays allowed: that changes only residual and payment state,
 * which the hooks do not treat as ledger fields, and the payment itself is
 * dated in the open period.
 */
class PeriodLock
{
    /**
     * The permission, besides being the company's Company Admin, that lets a
     * user move the date (ACC-D2). Generated by Shield from the affix on the
     * accounting plugin's JournalEntryResource.
     */
    public const PERMISSION = 'unlock_period_accounting_journal::entry';

    /**
     * Move columns that change what the ledger says. Anything else (payment
     * state, residuals, the checked flag, chatter-driven touches) may still be
     * written on a locked entry.
     */
    public const MOVE_LEDGER_FIELDS = ['state', 'date', 'journal_id', 'currency_id', 'partner_id', 'move_type', 'company_id'];

    public const LINE_LEDGER_FIELDS = ['debit', 'credit', 'balance', 'amount_currency', 'account_id', 'partner_id', 'tax_line_id', 'move_id'];

    public function lockDateFor(?int $companyId): ?CarbonImmutable
    {
        if (! $companyId) {
            return null;
        }

        $date = LockDate::query()
            ->where('company_id', $companyId)
            ->orderByDesc('id')
            ->value('lock_date');

        return $date ? CarbonImmutable::parse($date)->startOfDay() : null;
    }

    public function isLocked(?int $companyId, CarbonInterface|string|null $date): bool
    {
        $lock = $this->lockDateFor($companyId);

        if (! $lock || ! $date) {
            return false;
        }

        return CarbonImmutable::parse($date)->startOfDay()->lte($lock);
    }

    /**
     * Called from Move's saving hook.
     *
     * @throws PeriodLockedException
     */
    public function assertMoveSavable(Move $move): void
    {
        if ($move->exists && ! $move->isDirty(self::MOVE_LEDGER_FIELDS)) {
            return;
        }

        $wasPosted = $move->exists && $move->getRawOriginal('state') === MoveState::POSTED->value;

        $isPosted = $this->stateValue($move->state) === MoveState::POSTED->value;

        // Both sides: posting into a closed month, and moving or reopening an
        // entry that already sits in one (resetting to draft, cancelling, or
        // re-dating it out of the period).
        if ($isPosted && $this->isLocked($move->company_id, $move->date)) {
            $this->refuse($move->company_id);
        }

        if ($wasPosted && $this->isLocked($move->getRawOriginal('company_id'), $move->getRawOriginal('date'))) {
            $this->refuse($move->getRawOriginal('company_id'));
        }
    }

    /**
     * @throws PeriodLockedException
     */
    public function assertMoveDeletable(Move $move): void
    {
        if ($move->getRawOriginal('state') === MoveState::POSTED->value
            && $this->isLocked($move->getRawOriginal('company_id'), $move->getRawOriginal('date'))) {
            $this->refuse($move->getRawOriginal('company_id'));
        }
    }

    /**
     * Called from MoveLine's saving and deleting hooks. The parent is read
     * scope-free: a scoped read misses for anyone not entitled to it, and a
     * missing parent would let the change through.
     *
     * @throws PeriodLockedException
     */
    public function assertLineWritable(MoveLine $line, bool $deleting = false): void
    {
        if (! $deleting && $line->exists && ! $line->isDirty(self::LINE_LEDGER_FIELDS)) {
            return;
        }

        $moveIds = array_unique(array_filter([$line->move_id, $line->getRawOriginal('move_id')]));

        $moves = Move::withoutGlobalScopes()
            ->whereIn('id', $moveIds)
            ->get(['id', 'state', 'date', 'company_id']);

        foreach ($moves as $move) {
            if ($this->stateValue($move->state) === MoveState::POSTED->value
                && $this->isLocked($move->company_id, $move->date)) {
                $this->refuse($move->company_id);
            }
        }
    }

    public function mayChange(?User $user, int $companyId): bool
    {
        if (! $user) {
            return false;
        }

        if ($user->isSuperAdmin()) {
            return true;
        }

        // A global Company Admin role answers true for every company id, and
        // a permission is not company-bound either, so membership is what
        // keeps one tenant's accountant from moving another tenant's lock.
        $isMember = $user->allowedCompanies()
            ->withoutGlobalScopes()
            ->where('companies.id', $companyId)
            ->exists();

        return $isMember && ($user->isCompanyAdmin($companyId) || $user->can(self::PERMISSION));
    }

    /**
     * Set or clear (null) the company's lock date. Every call adds a history
     * row; nothing is updated in place.
     *
     * @throws AuthorizationException when the user may not move the date
     * @throws ValidationException when the date is in the future
     */
    public function setLockDate(int $companyId, User $actor, CarbonInterface|string|null $date): LockDate
    {
        if (! $this->mayChange($actor, $companyId)) {
            throw new AuthorizationException(__('accounts::account-manager.lock-date.not-allowed'));
        }

        $date = $date ? CarbonImmutable::parse($date)->startOfDay() : null;

        // A lock in the future would refuse today's invoices as soon as it is
        // saved; closing a period only ever looks back.
        if ($date && $date->isAfter(now()->startOfDay())) {
            throw ValidationException::withMessages([
                'lock_date' => __('accounts::account-manager.lock-date.future'),
            ]);
        }

        return LockDate::query()->create([
            'company_id'         => $companyId,
            'lock_date'          => $date?->toDateString(),
            'previous_lock_date' => $this->lockDateFor($companyId)?->toDateString(),
            'changed_by'         => $actor->getKey(),
        ]);
    }

    protected function refuse(?int $companyId): never
    {
        throw new PeriodLockedException(__('accounts::account-manager.lock-date.locked', [
            'date' => $this->lockDateFor($companyId)?->toDateString(),
        ]));
    }

    protected function stateValue(mixed $state): ?string
    {
        return $state instanceof MoveState ? $state->value : $state;
    }
}
